const assert=require('node:assert/strict');
const {createBrewDraftStore,brewWaterTotals,resizeBrewStages}=require('./dist/brew-flow.js');
const {scaleRecipe}=require('./dist/recipe-scale.js');
const steps=[{action:'注水',water:40,temp:90,start:'0:00',until:'0:30',actualWater:41,actualTemp:89,actualTime:'0:31',note:'累積 40g'},{action:'等待浸泡',water:0,start:'0:30',until:'1:00'},{action:'注水',water:80,temp:75,start:'1:00',until:'2:00'}];
const original=JSON.stringify(steps);
const adjusted=resizeBrewStages(steps,200,scaleRecipe);
assert.deepEqual(adjusted.filter(s=>s.action==='注水').map(s=>s.water),[66.7,133.3]);
assert.equal(adjusted[0].temp,90);assert.equal(adjusted[2].temp,75);
assert.equal(adjusted[1].action,'等待浸泡');assert.equal(adjusted[1].start,'0:30');
assert.equal(adjusted[0].actualWater,41);assert.equal(adjusted[0].actualTemp,89);assert.equal(adjusted[0].actualTime,'0:31');
assert.equal(JSON.stringify(steps),original,'original stages remain intact');
assert.equal(brewWaterTotals(adjusted,200).aligned,true);
assert.equal(brewWaterTotals(steps,200).difference,80);
assert.throws(()=>resizeBrewStages([],200,scaleRecipe));assert.throws(()=>resizeBrewStages(steps,0,scaleRecipe));
const values=new Map(),storage={getItem:k=>values.get(k)||null,setItem:(k,v)=>values.set(k,v)};
const a=createBrewDraftStore(storage,'A'),b=createBrewDraftStore(storage,'B');
const draft={id:'draft-one',fields:{bean:'私人咖啡豆',dose:'12.5',notes:'未寫完',waterMix:'{"hot":100,"room":26}'},stages:steps,editing:'brew-one',savedAt:100};
a.save(draft);a.save({...draft,id:'draft-two',fields:{...draft.fields,bean:'另一杯'}});
assert.equal(a.list().length,2);assert.equal(b.list().length,0,'account isolation');
const reload=createBrewDraftStore(storage,'A');assert.deepEqual(reload.list().find(d=>d.id===draft.id),draft,'complete form and measurements survive reload');
reload.save({...draft,fields:{...draft.fields,notes:'繼續寫'}});assert.equal(reload.list().length,2);
reload.remove('draft-one');assert.equal(reload.list()[0].id,'draft-two','successful save removes only its own draft');
b.save({...draft,id:'other'});assert.equal(a.list().length,1);assert.equal(b.list().length,1);
storage.setItem(a.key,'broken-data');assert.throws(()=>a.save(draft));assert.equal(storage.getItem(a.key),'broken-data','unreadable drafts never silently overwritten');
const failing=createBrewDraftStore({getItem:()=>null,setItem:()=>{throw Error('quota')}},'A');assert.throws(()=>failing.save(draft),/quota/);
console.log('Brew flow: exact proportional allocation, preserved timings/measurements, complete draft recovery, multiple drafts, account isolation, corruption and storage-failure safety passed.');
